// rvk_embed: the build-time text embedder (the HLSL sources of shaders/**, docs/research/hlsl-rhi.md 2).
//
//   rvk_embed <in> -o <out.h> --name <ident>
//       embeds a text file as `inline constexpr char <ident>[]` (null-terminated) in namespace rvk::shader::embedded::data.
//
// No dependencies beyond the standard library: the shaders are compiled at run time by DXC (shader/dxc.h), nothing is compiled at build time.

#include <cstdio>
#include <filesystem>
#include <format>
#include <fstream>
#include <sstream>
#include <string>

namespace fs = std::filesystem;

namespace {

bool readFile(const fs::path& p, std::string& out) {
    std::ifstream in(p, std::ios::binary);
    if (!in) return false;
    std::ostringstream ss;
    ss << in.rdbuf();
    out = ss.str();
    return true;
}

bool writeFile(const fs::path& p, const std::string& data) {
    std::error_code ec;
    if (p.has_parent_path()) fs::create_directories(p.parent_path(), ec);
    std::ofstream out(p, std::ios::binary);
    out.write(data.data(), static_cast<std::streamsize>(data.size()));
    return static_cast<bool>(out);
}

}  // namespace

int main(int argc, char** argv) {
    fs::path in, out;
    std::string name;
    for (int i = 1; i < argc; ++i) {
        const std::string a = argv[i];
        if (a == "-o" && i + 1 < argc) out = argv[++i];
        else if (a == "--name" && i + 1 < argc) name = argv[++i];
        else in = a;
    }
    if (in.empty() || out.empty() || name.empty()) {
        std::fprintf(stderr, "usage: rvk_embed <in> -o <out.h> --name <ident>\n");
        return 2;
    }
    std::string source;
    if (!readFile(in, source)) {
        std::fprintf(stderr, "%s: cannot read\n", in.generic_string().c_str());
        return 1;
    }
    std::string body = std::format("// {} bytes of text (null-terminated)\ninline constexpr char {}[] = {{", source.size(), name);
    for (std::size_t i = 0; i < source.size(); ++i) {
        body += i % 16 == 0 ? "\n    " : " ";
        body += std::format("{},", static_cast<int>(static_cast<unsigned char>(source[i])));
    }
    body += "\n    0,\n};\n\n";
    const std::string text = std::format(
        "// generated by rvk_embed from {}: do not edit\n#pragma once\n\nnamespace rvk::shader::embedded::data {{\n\n{}}}  // namespace rvk::shader::embedded::data\n",
        in.filename().generic_string(), body);
    if (!writeFile(out, text)) {
        std::fprintf(stderr, "%s: cannot write\n", out.generic_string().c_str());
        return 1;
    }
    return 0;
}

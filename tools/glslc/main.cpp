// rvk_glslc: the build-time GLSL compiler of hand-written shaders (shaders/**, docs/research/injection.md 2).
//
//   rvk_glslc compile <in.{vert,frag,comp}> -o <out.h> --name <ident> [-I <dir>]... [--depfile <out.d>] [--spv <out.spv>]
//       GLSL 4.60 -> SPIR-V 1.6 (Vulkan 1.3) with glslang, validated with spirv-val (SPIRV-Tools), written as a C++ header
//       with `inline constexpr std::uint32_t <ident>[]`. #include "..." is resolved against the including file's directory,
//       then the -I directories; the depfile lists every included file (CMake DEPFILE: edits of an include rebuild).
//   rvk_glslc text <in> -o <out.h> --name <ident>
//       embeds a text file (shaders/include/rvk_abi.glsl for the D3D9 translator) as `inline constexpr char <ident>[]`.
//
// Built from the vcpkg glslang + SPIRV-Tools libraries the renderer already links, so nothing beyond vcpkg is needed (no
// Vulkan SDK on the build machine). Errors go to stderr in "file:line: message" form (glslang's own) and fail the build.


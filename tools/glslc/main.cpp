#include <cstdio>
#include <filesystem>
#include <format>
#include <fstream>
#include <memory>
#include <set>
#include <sstream>
#include <string>
#include <string_view>
#include <vector>

#include <glslang/Public/ResourceLimits.h>
#include <glslang/Public/ShaderLang.h>
#include <glslang/SPIRV/GlslangToSpv.h>
#include <spirv-tools/libspirv.hpp>

namespace fs = std::filesystem;

namespace {

bool readFile(const fs::path& p, std::string& out) {
    std::ifstream in(p, std::ios::binary);
    if (!in) return false;
    std::ostringstream ss;
    ss << in.rdbuf();
    out = ss.str();
    return true;
}

bool writeFile(const fs::path& p, std::string_view data) {
    std::error_code ec;
    if (p.has_parent_path()) fs::create_directories(p.parent_path(), ec);
    std::ofstream out(p, std::ios::binary);
    out.write(data.data(), static_cast<std::streamsize>(data.size()));
    return static_cast<bool>(out);
}

std::string depPath(const fs::path& p) {
    std::string s = fs::absolute(p).lexically_normal().generic_string();
    std::string out;
    for (char c : s) {
        if (c == ' ' || c == '#') out += '\\';
        if (c == '$') out += '$';
        out += c;
    }
    return out;
}

class Includer final : public glslang::TShader::Includer {
public:
    explicit Includer(std::vector<fs::path> dirs) : dirs_(std::move(dirs)) {}
    std::set<fs::path> included;

    IncludeResult* includeLocal(const char* header, const char* includer, size_t) override {
        std::vector<fs::path> candidates;
        if (includer != nullptr && *includer != '\0') candidates.push_back(fs::path(includer).parent_path() / header);
        for (const auto& d : dirs_) candidates.push_back(d / header);
        return open(header, candidates);
    }
    IncludeResult* includeSystem(const char* header, const char*, size_t) override {
        std::vector<fs::path> candidates;
        for (const auto& d : dirs_) candidates.push_back(d / header);
        return open(header, candidates);
    }
    void releaseInclude(IncludeResult* r) override {
        if (r != nullptr) {
            delete static_cast<std::string*>(r->userData);
            delete r;
        }
    }

private:
    IncludeResult* open(const char* header, const std::vector<fs::path>& candidates) {
        for (const auto& c : candidates) {
            auto text = std::make_unique<std::string>();
            if (fs::is_regular_file(c) && readFile(c, *text)) {
                const fs::path abs = fs::absolute(c).lexically_normal();
                included.insert(abs);
                auto* s = text.release();
                return new IncludeResult(abs.generic_string(), s->data(), s->size(), s);
            }
        }
        (void)header;
        return nullptr;  // glslang reports "cannot find include file"
    }
    std::vector<fs::path> dirs_;
};

bool stageOf(const fs::path& p, EShLanguage& out) {
    const std::string ext = p.extension().string();
    if (ext == ".vert") out = EShLangVertex;
    else if (ext == ".frag") out = EShLangFragment;
    else if (ext == ".comp") out = EShLangCompute;
    else if (ext == ".geom") out = EShLangGeometry;
    else if (ext == ".tesc") out = EShLangTessControl;
    else if (ext == ".tese") out = EShLangTessEvaluation;
    else return false;
    return true;
}

std::string header(const fs::path& in, std::string_view body) {
    return std::format("// generated by rvk_glslc from {}: do not edit\n#pragma once\n\n#include <cstdint>\n\nnamespace rvk::shader::embedded::data {{\n\n{}}}  // namespace rvk::shader::embedded::data\n",
                       in.filename().generic_string(), body);
}

int compile(const fs::path& in, const fs::path& out, const std::string& name, const std::vector<fs::path>& dirs,
            const fs::path& depfile, const fs::path& spvOut, const std::vector<std::string>& defines) {
    EShLanguage stage{};
    if (!stageOf(in, stage)) {
        std::fprintf(stderr, "%s: unknown shader stage (extension .vert / .frag / .comp / .geom / .tesc / .tese)\n",
                     in.generic_string().c_str());
        return 1;
    }
    std::string source;
    if (!readFile(in, source)) {
        std::fprintf(stderr, "%s: cannot read\n", in.generic_string().c_str());
        return 1;
    }
    glslang::InitializeProcess();
    int result = 1;
    {
        glslang::TShader shader(stage);
        const std::string inName = fs::absolute(in).lexically_normal().generic_string();
        const char* text = source.c_str();
        const int length = static_cast<int>(source.size());
        const char* names = inName.c_str();
        shader.setStringsWithLengthsAndNames(&text, &length, &names, 1);
        std::string preamble = "#extension GL_GOOGLE_include_directive : require\n";
        for (const std::string& d : defines) {
            const auto eq = d.find('=');
            preamble += eq == std::string::npos ? "#define " + d + " 1\n" : "#define " + d.substr(0, eq) + " " + d.substr(eq + 1) + "\n";
        }
        shader.setPreamble(preamble.c_str());
        shader.setEnvInput(glslang::EShSourceGlsl, stage, glslang::EShClientVulkan, 100);
        shader.setEnvClient(glslang::EShClientVulkan, glslang::EShTargetVulkan_1_3);
        shader.setEnvTarget(glslang::EShTargetSpv, glslang::EShTargetSpv_1_6);
        const auto messages = static_cast<EShMessages>(EShMsgSpvRules | EShMsgVulkanRules);
        Includer includer(dirs);
        std::vector<std::uint32_t> words;
        if (!shader.parse(GetDefaultResources(), 460, false, messages, includer)) {
            std::fprintf(stderr, "%s\n", shader.getInfoLog());
        } else {
            glslang::TProgram program;
            program.addShader(&shader);
            if (!program.link(messages)) {
                std::fprintf(stderr, "%s\n", program.getInfoLog());
            } else {
                glslang::SpvOptions options;
                options.generateDebugInfo = false;
                options.disableOptimizer = false;
                spv::SpvBuildLogger logger;
                glslang::GlslangToSpv(*program.getIntermediate(stage), words, &logger, &options);
                if (const std::string msgs = logger.getAllMessages(); !msgs.empty()) std::fprintf(stderr, "%s", msgs.c_str());
            }
        }
        if (!words.empty()) {
            spvtools::SpirvTools tools(SPV_ENV_VULKAN_1_3);
            std::string validation;
            tools.SetMessageConsumer([&](spv_message_level_t, const char*, const spv_position_t& pos, const char* msg) {
                validation += std::format("  word {}: {}\n", pos.index, msg);
            });
            if (!tools.Validate(words)) {
                std::fprintf(stderr, "%s: spirv-val failed:\n%s", in.generic_string().c_str(), validation.c_str());
                words.clear();
            }
        }
        if (!words.empty()) {
            std::string body = std::format("// {} words, {} bytes of SPIR-V 1.6\ninline constexpr std::uint32_t {}[] = {{", words.size(),
                                           words.size() * 4, name);
            for (std::size_t i = 0; i < words.size(); ++i) {
                body += i % 8 == 0 ? "\n    " : " ";
                body += std::format("0x{:08x},", words[i]);
            }
            body += "\n};\n\n";
            bool ok = writeFile(out, header(in, body));
            if (ok && !spvOut.empty()) {
                ok = writeFile(spvOut, std::string_view(reinterpret_cast<const char*>(words.data()), words.size() * 4));
            }
            if (ok && !depfile.empty()) {
                std::string d = depPath(out) + ":";
                d += " \\\n  " + depPath(in);
                for (const auto& p : includer.included) d += " \\\n  " + depPath(p);
                ok = writeFile(depfile, d + "\n");
            }
            result = ok ? 0 : 1;
            if (!ok) std::fprintf(stderr, "%s: cannot write the outputs\n", out.generic_string().c_str());
        }
    }
    glslang::FinalizeProcess();
    return result;
}

int text(const fs::path& in, const fs::path& out, const std::string& name) {
    std::string source;
    if (!readFile(in, source)) {
        std::fprintf(stderr, "%s: cannot read\n", in.generic_string().c_str());
        return 1;
    }
    std::string body = std::format("// {} bytes of text (null-terminated)\ninline constexpr char {}[] = {{", source.size(), name);
    for (std::size_t i = 0; i < source.size(); ++i) {
        body += i % 16 == 0 ? "\n    " : " ";
        body += std::format("{},", static_cast<int>(static_cast<unsigned char>(source[i])));
    }
    body += "\n    0,\n};\n\n";
    if (!writeFile(out, header(in, body))) {
        std::fprintf(stderr, "%s: cannot write\n", out.generic_string().c_str());
        return 1;
    }
    return 0;
}

int usage() {
    std::fprintf(stderr,
                 "usage: rvk_glslc compile <in> -o <out.h> --name <ident> [-I <dir>]... [--depfile <out.d>] [--spv <out.spv>] [-D NAME[=VALUE]]...\n"
                 "       rvk_glslc text <in> -o <out.h> --name <ident>\n");
    return 2;
}

}  // namespace

int main(int argc, char** argv) {
    if (argc < 3) return usage();
    const std::string mode = argv[1];
    fs::path in = argv[2], out, depfile, spv;
    std::string name;
    std::vector<fs::path> dirs;
    std::vector<std::string> defines;
    for (int i = 3; i < argc; ++i) {
        const std::string a = argv[i];
        const bool hasValue = i + 1 < argc;
        if (a == "-o" && hasValue) out = argv[++i];
        else if (a == "--name" && hasValue) name = argv[++i];
        else if (a == "-I" && hasValue) dirs.emplace_back(argv[++i]);
        else if (a == "--depfile" && hasValue) depfile = argv[++i];
        else if (a == "--spv" && hasValue) spv = argv[++i];
        else if (a == "-D" && hasValue) defines.emplace_back(argv[++i]);
        else return usage();
    }
    if (out.empty() || name.empty()) return usage();
    if (mode == "compile") return compile(in, out, name, dirs, depfile, spv, defines);
    if (mode == "text") return text(in, out, name);
    return usage();
}
